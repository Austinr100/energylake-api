def load(name):
    return (json.loads((HERE / "prod" / name).read_text()),
            json.loads((HERE / name).read_text()))


def diff(a, b, path=""):
    """Paths that differ: +added, -removed, ~changed (lists of equal length walked)."""
    out = []
    if isinstance(a, dict) and isinstance(b, dict):
        for k in list(a) + [k for k in b if k not in a]:
            if k not in a:
                out.append(f"+{path}.{k}")
            elif k not in b:
                out.append(f"-{path}.{k}")
            else:
                out += diff(a[k], b[k], f"{path}.{k}")
    elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for x, y in zip(a, b):
            out += diff(x, y, f"{path}[]")
    elif a != b:
        out.append(f"~{path}")
    return out


def cells(body):
    return {(p["place_kind"], p["place"], p["weighting"], pr["product"], c["season"],
             c["strength"]): c
            for p in body["places"] for pr in p["products"]
            for s in pr["seasons"] for c in s["cells"]}


def place_name(r):
    return r["place"] + (f" ({r['weighting']})" if r["weighting"] else "")


